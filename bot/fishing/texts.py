def format_week_rewards_announce(
    *,
    details: list[dict],
    fow: dict | None,
    fow_bonus: int,
    payouts: dict[str, int],
) -> str:
    """Текст в чат после ручной выдачи недельных наград."""
    total = sum(int(v) for v in payouts.values())
    if total <= 0:
        return pick(ADMIN_REWARDS_CHAT_EMPTY)

    parts: list[str] = []
    for row in details:
        name = row.get("user_name") or row.get("user_id") or "?"
        species = row.get("species") or "?"
        reward = int(row.get("reward") or 0)
        if reward <= 0:
            continue
        parts.append(f"{species}: {name} (+{reward})")

    if fow is not None and fow_bonus > 0:
        name = fow.get("user_name") or fow.get("user_id") or "?"
        species = fow.get("species") or "?"
        weight = float(fow.get("weight") or 0)
        parts.append(
            f"рыба недели: {name} — {species} {weight:.2f} кг (+{fow_bonus})"
        )

    payouts_str = "; ".join(parts) if parts else "—"
    return pick(ADMIN_REWARDS_CHAT).format(payouts=payouts_str, total=total)


def pick(pool: Sequence[str]) -> str:
    return random.choice(tuple(pool))


def format_resources(
    energy: int,
    worms: int,
    maggots: int,
    rod_state: str,
    *,
    mermaid_shields: int = 0,
    bite_boost_casts_left: int = 0,
    steal_safe: bool = False,
) -> str:
    """Компактный хвост после заброса/покупок. Баффы — только если активны."""
    if rod_state == "ok":
        rod = "целая"
    elif rod_state == "broken":
        rod = "сломана — нужна новая"
    else:
        rod = "нет"
    bait = int(worms) + int(maggots)
    parts = [
        f"Энергия: {energy}/100",
        f"Наживка: {bait}",
        f"Удочка: {rod}",
    ]
    shields = int(mermaid_shields or 0)
    if shields > 0:
        parts.append(f"Щиты: {shields}")
    boost = int(bite_boost_casts_left or 0)
    if boost > 0:
        parts.append(f"Буст: {boost}")
    if steal_safe:
        parts.append("Сейф")
    return " | ".join(parts)


def resources_from_player(player: dict) -> str:
    return format_resources(
        int(player["energy"]),
        int(player["worms"]),
        int(player["maggots"]),
        str(player["rod_state"]),
        mermaid_shields=int(player.get("mermaid_shields") or 0),
        bite_boost_casts_left=int(player.get("bite_boost_casts_left") or 0),
        steal_safe=bool(player.get("steal_safe")),
    )


def safe_label(steal_safe: bool) -> str:
    return "да" if steal_safe else "нет"


def rod_label(rod_state: str) -> str:
    if rod_state == "ok":
        return "целая"
    if rod_state == "broken":
        return "сломана — нужна новая"
    return "нет"


def rod_hint(rod_state: str) -> str:
    if rod_state == "ok":
        return "целая"
    if rod_state == "broken":
        return "сломана — !рыбалка удочка"
    return "нет — !рыбалка удочка"
